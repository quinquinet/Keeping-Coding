#include <string.h>
#include <stdlib.h>

char *ft_strdup(char *src);

int main(int ac, char **av)
{
    if (ac != 2)
        return (-1);    

    char *src = av[1];
    char *ft_dest;
    char *real_dest;
    
    ft_dest = ft_strdup(src);
    real_dest = strdup(src);

    int ret = strcmp(ft_dest, real_dest);

    free(ft_dest);
    free(real_dest);

    return (ret);
}